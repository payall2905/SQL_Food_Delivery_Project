-- ** QUESTIONS OF JOINS, GROUP BY, ORDER BY AND SOME OF INTERMEDIATE**

-- WHICH RESTAURANT HAS RECEIVED THE HIGHEST NUMBER OF ORDERS?
SELECT TABLE2.restaurant_id, COUNT(*) AS TOTAL_ORDERS
from restaurant_project.orders_medium AS TABLE1
INNER JOIN
restaurant_project.restaurants AS TABLE2
ON TABLE1.restaurant_id = TABLE2.restaurant_id
GROUP BY TABLE2.restaurant_id
ORDER BY TOTAL_ORDERS DESC
LIMIT 1;

-- WHICH CUSTOMERS HAVE PLACED MORE THAN 5 ORDERS?
SELECT T2.customer_id, COUNT(order_id) AS NUMBER_OF_ORDERS  
from restaurant_project.orders_medium AS T1
inner join restaurant_project.customers_medium AS T2
ON T1.customer_id = T2.customer_id
GROUP BY T2.customer_id
HAVING NUMBER_OF_ORDERS > 5 ;

-- WHICH 10 MENU ITEMS ARE ORDERED MOST FREQUENTLY?
SELECT  T2.item_id ,count(T1.order_id) AS MOST_ORDERED 
FROM restaurant_project.`order_items (2)` AS T1
INNER JOIN restaurant_project.menu_items AS T2
ON T1.item_id = T2.item_id
GROUP BY T2.item_id
ORDER BY MOST_ORDERED DESC
LIMIT 10;

-- CALCULATE TOTAL REVENUE GENERATED BY EACH RESTAURANT AND DISPLAY THE RESTAURANTS FROM HIGHEST TO LOWEST REVENUE?
SELECT  T2.restaurant_id ,SUM(T1.price) AS TOTAL_REVENUE
FROM restaurant_project.`order_items (2)` AS T1
INNER JOIN restaurant_project.orders_medium AS T2
ON T1.order_id = T2.order_id
GROUP BY T2.restaurant_id
order by TOTAL_REVENUE desc;
